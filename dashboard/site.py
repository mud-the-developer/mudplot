def _generate_reading_examples(out: Path) -> str:
    """Rebuild the reviewed layouts; keep review/docs/exports usable offline."""
    from examples.publication_showcase import render_examples

    root = Path(__file__).resolve().parents[1] / "docs"
    directory = out / "reading"
    render_examples(directory / "images")
    review = (root / "VISUAL_REVIEW.html").read_text(encoding="utf-8")
    for filename, lang in (("VISUAL_QUALITY.md", "en"), ("VISUAL_QUALITY.ko.md", "ko")):
        target = filename.removesuffix(".md") + ".html"
        review = review.replace(filename, target)
        body = markdown_to_html((root / filename).read_text(encoding="utf-8"))
        for source in ("VISUAL_QUALITY.md", "VISUAL_QUALITY.ko.md"):
            body = body.replace(source, source.removesuffix(".md") + ".html")
        (directory / target).write_text(
            _READING_DOC_PAGE.format(lang=lang, body=body), encoding="utf-8"
        )
    (directory / "VISUAL_REVIEW.html").write_text(review, encoding="utf-8")
    shutil.copyfile(
        root / "images/visual_after.png", directory / "images/visual_after.png"
    )
    return (
        "<p>One question per chart, with captions and editable specs. "
        '<a href="reading/VISUAL_REVIEW.html">Open the actual-size desktop/mobile '
        "review</a>. Independent reader evaluation is still pending.</p>"
        '<figure class="reading-example"><picture>'
        '<source media="(max-width: 739px)" '
        'srcset="reading/images/visual_response_mobile.png">'
        '<img src="reading/images/visual_response.png" width="700" height="400" '
        'alt="Mean response with direct method labels and pointwise confidence bands">'
        "</picture><figcaption>Independent synthetic observations; n = 12 per "
        "method/timepoint. Shading is a pointwise 95% CI of the mean. "
        '<a href="reading/images/visual_response.mplot.json">Response spec</a> · '
        '<a href="reading/images/visual_endpoint.mplot.json">Endpoint spec</a>. '
        "Download a spec and open it in the editor; these links do not replace "
        "an editor session.</figcaption></figure>"
    )


def _figure_html(src: str, caption: str) -> str:
    return (
        f'<figure><img src="{src}" alt="{caption}">'
        f"<figcaption>{caption}</figcaption></figure>"
    )


def _generate_gallery_images(gallery_dir: Path) -> list[tuple[str, str]]:
    """Render the design-principle demo figures; returns (filename, caption)."""
    import matplotlib

    matplotlib.use("Agg")
    import mudplot as mp
    import numpy as np
    from mudplot.color import palette as P
    from mudplot.color.preview import preview

    gallery_dir.mkdir(parents=True, exist_ok=True)
    items: list[tuple[str, str]] = []

    # 1. Qualitative palette: CVD + greyscale safety
    import matplotlib.pyplot as plt

    fig, ax = plt.subplots(figsize=(6.5, 2.6))
    preview(P.qualitative(5), ax=ax)
    fig.tight_layout()
    fig.savefig(gallery_dir / "palette_safety.png", dpi=140)
    plt.close(fig)
    items.append(
        (
            "palette_safety.png",
            "Qualitative palette under normal vision, two CVD simulations, and "
            "true greyscale — equal-ish lightness + a small jitter keeps every "
            "swatch distinguishable in all four.",
        )
    )

    # 2. Redundant encoding: marker + dash + colour, shown in colour and grey
    rng = np.random.default_rng(0)
    x = np.linspace(0, 10, 60)
    data = {
        "x": list(x) * 3,
        "y": list(np.sin(x)) + list(np.sin(x) * 0.6) + list(np.sin(x) * 0.3),
        "g": ["A"] * 60 + ["B"] * 60 + ["C"] * 60,
    }
    p = (
        mp.plot(data)
        .line("x", "y", group="g")
        .legend(title="series")
        .labels(title="redundant encoding: colour + marker + dash")
    )
    # tight=True: these are illustrative web-gallery images, not journal
    # figures -- physical inch size doesn't matter here, but content (e.g.
    # this title) shouldn't get silently clipped at the default exact size.
    plt.close(p.save(str(gallery_dir / "redundant_encoding.png"), tight=True))
    items.append(
        (
            "redundant_encoding.png",
            "Grouped series get a distinct marker and dash pattern in addition "
            "to colour, so comparisons survive greyscale print or colour-vision "
            "deficiency.",
        )
    )

    # 3. TeX WYSIWYG preview
    p2 = (
        mp.plot(data)
        .line("x", "y", group="g")
        .labels(x="t", y="signal")
        .legend(title="series")
    )
    fig3 = p2.preview(tex="ieee", caption="Figure 1. Example signal comparison.")
    fig3.savefig(gallery_dir / "tex_preview.png", dpi=140, bbox_inches="tight")
    plt.close(fig3)
    items.append(
        (
            "tex_preview.png",
            "TeX-aware preview: the figure is rendered at its true final size and "
            "font inside a mock IEEE column, so you see exactly what the paper "
            "will show.",
        )
    )

    # 4. Secondary axis + colour-mapped scatter + heatmap (render coverage)
    n = 40
    xs = np.linspace(0, 10, n)
    data2 = {
        "x": list(xs),
        "temp": list(20 + 5 * np.sin(xs)),
        "pressure": list(1000 + 40 * np.cos(xs * 0.5)),
        "val": list(rng.normal(size=n)),
    }
    p3 = (
        mp.plot(data2)
        .secondary_yaxis("Pressure (hPa)")
        .line("x", "temp", label="Temp")
        .line("x", "pressure", label="Pressure", axis="y2", color="#888888")
        .legend(location="outside right")
        .axes_style(spine_offset=6)
    )
    plt.close(p3.save(str(gallery_dir / "secondary_axis.png"), tight=True))
    items.append(
        (
            "secondary_axis.png",
            "Secondary y-axis, an outside-right legend, and offset ('despine') "
            "spines for a clean, Tufte-style look.",
        )
    )

    mat = (rng.normal(size=(18, 26)) + np.sin(np.linspace(0, 6, 26))).tolist()
    p4 = (
        mp.plot({})
        .matrix("m", mat)
        .heatmap("m", clabel="value", cmap_kind="diverging")
        .labels(title="LCH diverging heatmap")
    )
    plt.close(p4.save(str(gallery_dir / "heatmap.png"), tight=True))
    items.append(
        (
            "heatmap.png",
            "Heatmap and colour-mapped scatter use the same LCH sequential / "
            "diverging colormaps as the categorical palettes — perceptually "
            "uniform end to end.",
        )
    )

    return items


def _plot_gallery_html() -> str:
    from mudplot.capabilities import LAYER_TYPES

    sections = []
    for category, title, title_ko in GALLERY_CATEGORIES:
        cards = []
        for example in GALLERY_EXAMPLES:
            if example.category != category:
                continue
            fields = LAYER_TYPES[example.name]
            required = ", ".join(fields["required"])
            optional = ", ".join(fields["optional"]) or "—"
            code = html.escape(f'{example.code}\nplot.save("figure.png")')
            cards.append(
                f'<article class="plot-card" id="plot-{example.name}">'
                f"<h4><code>{example.name}</code> — {html.escape(example.title)}</h4>"
                f'<img loading="lazy" src="plots/{example.name}.png" '
                f'alt="{html.escape(example.description)}">'
                f"<p>{html.escape(example.description)}</p>"
                f'<p lang="ko">{html.escape(example.description_ko)}</p>'
                f'<p class="contract"><strong>Required:</strong> '
                f"{html.escape(required)}<br><strong>Optional:</strong> "
                f"{html.escape(optional)}</p>"
                f'<p><a href="plots/{example.name}.mplot.json">'
                "Editable spec / 편집 가능한 spec</a> · "
                '<a href="#reference">Engine reference</a></p>'
                "<details><summary>Runnable code / 실행 코드</summary>"
                f"<pre><code>{code}</code></pre></details></article>"
            )
        sections.append(
            f"<h3>{html.escape(title)} / {html.escape(title_ko)}</h3>"
            f'<div class="plot-grid">{"".join(cards)}</div>'
        )
    return "".join(sections)


@matplotlib_context()
def build_site(out_dir: str = "dashboard/site_build") -> Path:
    """Generate the static docs+gallery site into ``out_dir``. Returns its path."""
    import mudplot as mp

    out = Path(out_dir)
    gallery_dir = out / "gallery"
    items = _generate_gallery_images(gallery_dir)
    render_plot_gallery(out / "plots", write_specs=True)

    gallery_html = (
        '<div class="grid">\n'
        + "\n".join(_figure_html(f"gallery/{name}", caption) for name, caption in items)
        + "\n</div>"
    )

    reference_html = markdown_to_html(mp.reference_markdown())

    page = _PAGE.format(
        reading=_generate_reading_examples(out),
        plots=_plot_gallery_html(),
        gallery=gallery_html,
        reference=reference_html,
    )
    (out / "index.html").write_text(page, encoding="utf-8")
    return out
